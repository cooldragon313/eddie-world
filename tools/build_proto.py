"""Build a prototype page (prototypes/<name>.src.html -> prototypes/<name>.html)
with the storybook look copied out of island.html.

    python tools/build_proto.py eddie
    python tools/build_proto.py eddie --preview out.html   # shell-less copy for a claude.ai preview
"""
import argparse
import pathlib
import re

from build_race import block_until_function_end

ROOT = pathlib.Path(__file__).resolve().parent.parent


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('name')
    ap.add_argument('--preview')
    args = ap.parse_args()
    island = (ROOT / 'island.html').read_text(encoding='utf-8')
    look = block_until_function_end(island, '// STORYBOOK LOOK', 'sbOutline')
    src_path = ROOT / 'prototypes' / (args.name + '.src.html')
    src = src_path.read_text(encoding='utf-8')
    src = src.replace('/*@@INCLUDE:LOOK@@*/', '// ---- copied from island.html by tools/build_proto.py (LOOK) ----\n' + look)
    if '/*@@INCLUDE:AVATAR@@*/' in src:
        avatar = block_until_function_end(island, 'const DEFAULT_CUSTOM', 'buildAvatar')
        src = src.replace('/*@@INCLUDE:AVATAR@@*/', '// ---- copied from island.html by tools/build_proto.py (AVATAR) ----\n' + avatar)
    out = ROOT / 'prototypes' / (args.name + '.html')
    out.write_text('<!-- GENERATED by tools/build_proto.py — edit the .src.html -->\n' + src, encoding='utf-8', newline='\n')
    print('wrote', out)
    if args.preview:
        head = src.split('<head>', 1)[1].split('</head>', 1)[0]
        body = src.split('<body>', 1)[1].rsplit('</body>', 1)[0]
        head = re.sub(r'<meta[^>]*>\n?', '', head)
        pathlib.Path(args.preview).write_text(head.lstrip('\n') + body, encoding='utf-8', newline='\n')
        print('wrote preview', args.preview)


if __name__ == '__main__':
    main()
