"""Build the family mini-games (family/*.src.html) with the island's storybook look.

Same idea as build_race.py: the toon ramp, ink outlines and rounded boxes are
lifted out of island.html on every build, so the mini-games stay in the same
art style as the island and the race.

    python tools/build_family.py                      # writes gluenight.html
    python tools/build_family.py --preview out.html   # also a shell-less copy for a claude.ai preview
"""
import argparse
import pathlib
import re

from build_race import block_until_function_end

ROOT = pathlib.Path(__file__).resolve().parent.parent
GAMES = {'gluenight': 'family/gluenight.src.html'}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--preview', help='also write a copy without <html>/<head>/<body> for a claude.ai preview')
    args = ap.parse_args()

    island = (ROOT / 'island.html').read_text(encoding='utf-8')
    look = block_until_function_end(island, '// STORYBOOK LOOK', 'sbOutline')
    for name, src_path in GAMES.items():
        src = (ROOT / src_path).read_text(encoding='utf-8')
        marker = '/*@@INCLUDE:LOOK@@*/'
        if marker not in src:
            raise SystemExit('missing marker ' + marker + ' in ' + src_path)
        src = src.replace(marker, '// ---- copied from island.html by tools/build_family.py (LOOK) ----\n' + look)
        banner = '<!-- GENERATED by tools/build_family.py from ' + src_path + ' — edit the source, not this file. -->\n'
        out = ROOT / (name + '.html')
        out.write_text(banner + src, encoding='utf-8', newline='\n')
        print('wrote', out, len(src), 'chars')

        if args.preview:
            head = src.split('<head>', 1)[1].split('</head>', 1)[0]
            body = src.split('<body>', 1)[1].rsplit('</body>', 1)[0]
            head = re.sub(r'<meta[^>]*>\n?', '', head)
            pathlib.Path(args.preview).write_text(head.lstrip('\n') + body, encoding='utf-8', newline='\n')
            print('wrote preview', args.preview)


if __name__ == '__main__':
    main()
