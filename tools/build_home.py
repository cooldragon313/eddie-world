"""Build index.html (土星之家, the hub = the site's front page) from home/home.src.html.

Same idea as build_race.py: the storybook look and the avatar/cosmetics are
lifted out of island.html on every build so the home looks like the levels.

    python tools/build_home.py                      # writes index.html (+ home.html, a redirect for old links)
    python tools/build_home.py --preview out.html   # also a shell-less copy for a claude.ai preview
"""
import argparse
import pathlib
import re

from build_race import block_until_function_end

ROOT = pathlib.Path(__file__).resolve().parent.parent


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--preview', help='also write a copy without <html>/<head>/<body> for a claude.ai preview')
    args = ap.parse_args()

    island = (ROOT / 'island.html').read_text(encoding='utf-8')
    blocks = {
        'LOOK': block_until_function_end(island, '// STORYBOOK LOOK', 'sbOutline'),
        'AVATAR': block_until_function_end(island, 'const DEFAULT_CUSTOM', 'buildAvatar'),
    }
    src = (ROOT / 'home' / 'home.src.html').read_text(encoding='utf-8')
    for name, code in blocks.items():
        marker = '/*@@INCLUDE:' + name + '@@*/'
        if marker not in src:
            raise SystemExit('missing marker ' + marker)
        src = src.replace(marker, '// ---- copied from island.html by tools/build_home.py (' + name + ') ----\n' + code)
    banner = '<!-- GENERATED by tools/build_home.py from home/home.src.html — edit the source, not this file. -->\n'
    out = ROOT / 'index.html'
    out.write_text(banner + src, encoding='utf-8', newline='\n')
    print('wrote', out, len(src), 'chars')
    # home.html used to be the hub's address: keep it working
    (ROOT / 'home.html').write_text('<!doctype html><meta charset="utf-8"><title>土星之家</title>'
                                    '<meta http-equiv="refresh" content="0; url=index.html"><a href="index.html">土星之家</a>\n', encoding='utf-8', newline='\n')

    if args.preview:
        head = src.split('<head>', 1)[1].split('</head>', 1)[0]
        body = src.split('<body>', 1)[1].rsplit('</body>', 1)[0]
        head = re.sub(r'<meta[^>]*>\n?', '', head)
        pathlib.Path(args.preview).write_text(head.lstrip('\n') + body, encoding='utf-8', newline='\n')
        print('wrote preview', args.preview)


if __name__ == '__main__':
    main()
