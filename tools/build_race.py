"""Build index.html (the race = home page) from race/race.src.html + shared code copied out of island.html.

The spike-wall race reuses the island's storybook look, avatar/cosmetics and
bat swing. Instead of keeping a second copy by hand, this script lifts those
blocks out of island.html every build, so a change on the island (a new hat,
a tweak to the toon shading) reaches the race too.

    python tools/build_race.py                      # writes index.html
    python tools/build_race.py --preview out.html   # also a shell-less copy for a claude.ai preview
"""
import argparse
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent


def block_until_function_end(src, start_marker, func_name):
    """From start_marker up to the closing brace of `function func_name(`."""
    start = src.index(start_marker)
    fn = src.index('function ' + func_name + '(', start)
    i = src.index('{', fn)
    depth = 0
    for k in range(i, len(src)):
        if src[k] == '{':
            depth += 1
        elif src[k] == '}':
            depth -= 1
            if depth == 0:
                return src[start:k + 1]
    raise ValueError('unbalanced braces in ' + func_name)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--preview', help='also write a copy without <html>/<head>/<body> for a claude.ai preview')
    args = ap.parse_args()

    island = (ROOT / 'island.html').read_text(encoding='utf-8')
    blocks = {
        # toon materials + ink outlines + rounded boxes
        'LOOK': block_until_function_end(island, '// STORYBOOK LOOK', 'sbOutline'),
        # DEFAULT_CUSTOM, body scales, 20 cosmetics, bag skins, buildAvatar
        'AVATAR': block_until_function_end(island, 'const DEFAULT_CUSTOM', 'buildAvatar'),
        # two-handed bat swing pose
        'SWING': block_until_function_end(island, 'const SWING_DUR', 'poseBatSwing'),
    }
    src = (ROOT / 'race' / 'race.src.html').read_text(encoding='utf-8')
    for name, code in blocks.items():
        marker = '/*@@INCLUDE:' + name + '@@*/'
        if marker not in src:
            raise SystemExit('missing marker ' + marker)
        src = src.replace(marker, '// ---- copied from island.html by tools/build_race.py (' + name + ') ----\n' + code)
    banner = '<!-- GENERATED by tools/build_race.py from race/race.src.html — edit the source, not this file. -->\n'
    out = ROOT / 'index.html'
    out.write_text(banner + src, encoding='utf-8', newline='\n')
    print('wrote', out, len(src), 'chars')

    if args.preview:
        head = src.split('<head>', 1)[1].split('</head>', 1)[0]
        body = src.split('<body>', 1)[1].rsplit('</body>', 1)[0]
        head = re.sub(r'<meta[^>]*>\n?', '', head)
        pathlib.Path(args.preview).write_text(head.lstrip('\n') + body, encoding='utf-8', newline='\n')
        print('wrote preview', args.preview)


if __name__ == '__main__':
    main()
